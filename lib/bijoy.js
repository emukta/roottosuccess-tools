const CONS = "কখগঘঙচছজঝঞটঠডঢণতথদধনপফবভমযরলশষসহড়ঢ়য়ৎ";
const isCons = (c) => !!c && CONS.includes(c);
const PRE_KAR = "িেৈ";
const POST_SIGN = "াীুূৃৗ";
const HASANT = "্";

function buildMatcher(pairs) {
  const map = new Map();
  let maxLen = 1;
  for (const [k, v] of pairs) {
    if (!map.has(k)) map.set(k, v);
    if (k.length > maxLen) maxLen = k.length;
  }
  return (input) => {
    let out = "";
    let i = 0;
    while (i < input.length) {
      let hit = false;
      for (let len = Math.min(maxLen, input.length - i); len > 0; len--) {
        const piece = input.substr(i, len);
        if (map.has(piece)) {
          out += map.get(piece);
          i += len;
          hit = true;
          break;
        }
      }
      if (!hit) {
        out += input[i];
        i++;
      }
    }
    return out;
  };
}

const extraU2B = [];
for (const [h, hb] of Object.entries(HALF)) {
  for (const [s, sb] of Object.entries(SUB)) extraU2B.push([h + s.slice(1), hb + sb]);
}
const toBijoyMap = buildMatcher([...U2B, ...extraU2B]);
const toUnicodeMap = buildMatcher(B2U_EXTRA);

// ---------- Bijoy -> Unicode ----------
export function bijoyToUnicode(text) {
  if (!text) return "";
  let s = text
    .replace(/yy/g, "y").replace(/vv/g, "v")
    .replace(/‡u/g, "u‡").replace(/†u/g, "u†").replace(/wu/g, "uw");

  s = toUnicodeMap(s);
  s = s.replace(/্+/g, HASANT);

  const a = [...s];
  // 1) move pre-kar (and a chandrabindu stuck to it) after the consonant cluster
  for (let i = 0; i < a.length; i++) {
    if (!PRE_KAR.includes(a[i])) continue;
    let j = i + 1;
    let chandra = false;
    if (a[j] === "ঁ") { chandra = true; j++; }
    if (!isCons(a[j])) continue;
    let end = j + 1;
    while (a[end] === HASANT && isCons(a[end + 1])) end += 2;
    const cluster = a.slice(j, end);
    let kar = a[i];
    let skip = 0;
    if (kar === "ে" && a[end] === "া") { kar = "ো"; skip = 1; }
    else if (kar === "ে" && a[end] === "ৗ") { kar = "ৌ"; skip = 1; }
    const rebuilt = [...cluster, kar, ...(chandra ? ["ঁ"] : [])];
    a.splice(i, end - i + skip, ...rebuilt);
    i += rebuilt.length - 1;
  }
  // 2) move reph before its consonant cluster
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== REPH) continue;
    let k = i - 1;
    while (k >= 0 && "ািীুূৃেৈোৌৗ".includes(a[k])) k--;
    if (!isCons(a[k])) { a[i] = "র্"; continue; }
    while (k - 2 >= 0 && a[k - 1] === HASANT && isCons(a[k - 2])) k -= 2;
    a.splice(i, 1);
    a.splice(k, 0, "র্");
  }
  let out = a.join("");
  // 3) chandrabindu goes after post-kars
  out = out.replace(/ঁ([াীুূৃ])/g, "$1ঁ");
  out = out.replace(/অা/g, "আ").replace(/্+/g, HASANT).replace(new RegExp(REPH, "g"), "র্");
  out = out.replace(/([০-৯])ঃ/g, "$1:").replace(/ ঃ/g, ":");
  return out;
}

// ---------- Unicode -> Bijoy ----------
export function unicodeToBijoy(text) {
  if (!text) return "";
  let s = text
    .replace(/ো/g, "ো").replace(/ৌ/g, "ৌ")
    .replace(/ড়/g, "ড়").replace(/ঢ়/g, "ঢ়").replace(/য়/g, "য়")
    .replace(/ো/g, "ো").replace(/ৌ/g, "ৌ");

  const a = [...s];
  const out = [];
  let i = 0;
  while (i < a.length) {
    // র‌্য (র + ZWNJ + ্য) stays as-is (handled by map)
    const startsReph = a[i] === "র" && a[i + 1] === HASANT && isCons(a[i + 2]) && a[i - 1] !== HASANT;
    if (isCons(a[i]) || startsReph) {
      let j = i;
      let reph = false;
      if (startsReph) { reph = true; j = i + 2; }
      let end = j + 1;
      while (a[end] === HASANT && isCons(a[end + 1])) end += 2;
      const cluster = a.slice(j, end);
      let pre = "";
      const post = [];
      let k = end;
      if (a[k] === "ো") { pre = "ে"; post.push("া"); k++; }
      else if (a[k] === "ৌ") { pre = "ে"; post.push("ৗ"); k++; }
      else if (PRE_KAR.includes(a[k] || "\0")) { pre = a[k]; k++; }
      while (k < a.length && (POST_SIGN.includes(a[k]) || a[k] === "ঁ" || a[k] === "ং" || a[k] === "ঃ")) {
        post.push(a[k]); k++;
      }
      out.push(pre, ...cluster, reph ? REPH : "", ...post);
      i = k;
    } else {
      out.push(a[i]);
      i++;
    }
  }
  let res = out.join("");
  // ra-phala after a conjunct uses the narrow glyph (ª); after a single consonant, Ö
  res = res.replace(/([\u0995-\u09B9\u09DC\u09DD\u09DF])(্[\u0995-\u09B9\u09DC\u09DD\u09DF])্র/g, (m, c1, sub) =>
    ["ন্ত", "স্ত", "ম্প", "ম্ভ", "ষ্ক", "স্ক"].includes(c1 + sub) ? m : c1 + sub + "\uE001");
  res = toBijoyMap(res);
  return res;
}
